/// 按任意别名查找参数定义，返回其在注册表中的下标。
pub fn index_of(flag: &str) -> Option<usize> {
    REGISTRY.iter().position(|def| def.flags.contains(&flag))
}

#[cfg(test)]
mod tests {
    use super::{index_of, REGISTRY};
    use std::collections::HashSet;

    #[test]
    fn key_is_first_alias_and_flags_are_unique() {
        // 解析与重建都按 flags 匹配，别名重复会导致静默错配，必须唯一。
        let mut seen: HashSet<&str> = HashSet::new();
        for def in REGISTRY {
            assert_eq!(def.key, def.flags[0], "key 必须是首个别名：{}", def.key);
            for flag in def.flags {
                assert!(seen.insert(flag), "重复的 flag：{flag}");
            }
        }
    }

    #[test]
    fn every_alias_resolves_to_its_definition() {
        for def in REGISTRY {
            for flag in def.flags {
                let idx = index_of(flag).expect("别名应能命中定义");
                assert_eq!(REGISTRY[idx].key, def.key, "别名 {flag} 命中了下标 {idx}");
            }
        }
    }
}
