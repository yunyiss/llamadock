use serde::Serialize;

/// 参数类型；`Enum` 目前按普通文本框渲染（前端 `types.ts` 已对齐）。
#[allow(dead_code)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum ParamKind {
    Number,
    Bool,
    Path,
    String,
    Enum,
}

/// 参数分组（前端 `params.ts` 已对齐）。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum ParamGroup {
    Model,
    Server,
    Perf,
    Gpu,
    Sampling,
    Log,
}

pub struct ParamDef {
    /// 规范名（首个别名）
    pub key: &'static str,
    /// 全部别名
    pub flags: &'static [&'static str],
    pub kind: ParamKind,
    pub group: ParamGroup,
    /// 面板上显示的简短名称
    pub desc: &'static str,
    /// 点「?」时展示的详细说明
    pub detail: &'static str,
}

